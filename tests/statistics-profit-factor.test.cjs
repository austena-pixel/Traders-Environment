// Regression coverage for Profit Factor outcomes and the redesigned indicator card.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const html=fs.readFileSync(path.resolve(__dirname,'../t-ios.html'),'utf8');

const start=html.indexOf('function calculateProfitFactorStats(');
const end=html.indexOf('\nfunction renderStatisticsIndicators(',start);
assert.ok(start>=0&&end>start,'Profit Factor model and renderer must exist in t-ios.html');
const source=html.slice(start,end);
const ids=['statProfitFactorDiagramValue','statProfitFactorExplanation','statProfitFactorBar','statProfitFactorProfitFill','statProfitFactorLossFill','statProfitFactorGrossProfit','statProfitFactorGrossLoss'];
const elements=new Map(ids.map(id=>['#'+id,{textContent:'',className:'',style:{},attributes:{},setAttribute(name,value){this.attributes[name]=value}}]));
const context={Intl,Number,String,Array,Math,tradingAccount:{currency:'USD'},$:selector=>elements.get(selector)};
vm.runInNewContext(source,context);
const calculate=context.calculateProfitFactorStats;
const paint=trades=>context.renderProfitFactorIndicator(calculate(trades));
const value=()=>elements.get('#statProfitFactorDiagramValue');
const explanation=()=>elements.get('#statProfitFactorExplanation');

let stats=calculate([{pnl:652},{pnl:-100}]);
assert.equal(stats.grossProfit,652);
assert.equal(stats.grossLoss,100);
assert.equal(stats.value,6.52);
paint([{pnl:652},{pnl:-100}]);
assert.equal(value().textContent,'6.52×');
assert.match(value().className,/pos/);
assert.equal(elements.get('#statProfitFactorGrossProfit').textContent,'$652.00');
assert.equal(elements.get('#statProfitFactorGrossLoss').textContent,'$100.00');
context.tradingAccount.currency='EUR';
paint([{pnl:652},{pnl:-100}]);
assert.equal(elements.get('#statProfitFactorGrossProfit').textContent,new Intl.NumberFormat(undefined,{style:'currency',currency:'EUR',minimumFractionDigits:2,maximumFractionDigits:2}).format(652));
context.tradingAccount.currency='USD';
paint([{pnl:652},{pnl:-100}]);
assert.match(explanation().textContent,/\$1\.00 lost, \$6\.52/);
const profitWidth=parseFloat(elements.get('#statProfitFactorProfitFill').style.width);
const lossWidth=parseFloat(elements.get('#statProfitFactorLossFill').style.width);
assert.ok(Math.abs(profitWidth-652/752*100)<1e-10);
assert.ok(Math.abs(lossWidth-100/752*100)<1e-10);
assert.match(elements.get('#statProfitFactorBar').attributes['aria-label'],/Green represents gross profit; red represents gross loss/);

stats=calculate([{pnl:50},{pnl:-100}]);
assert.equal(stats.value,.5);
paint([{pnl:50},{pnl:-100}]);
assert.equal(value().textContent,'0.50×');
assert.match(value().className,/neg/);
stats=calculate([{pnl:125},{pnl:-125}]);
assert.equal(stats.value,1);
paint([{pnl:125},{pnl:-125}]);
assert.match(value().className,/neutral/);
stats=calculate([{pnl:40},{pnl:10}]);
assert.equal(stats.value,Infinity);
assert.equal(stats.state,'infinite');
paint([{pnl:40},{pnl:10}]);
assert.equal(value().textContent,'∞');
assert.match(explanation().textContent,/No losses recorded/);
stats=calculate([{pnl:-25}]);
assert.equal(stats.value,0);
paint([{pnl:-25}]);
assert.equal(value().textContent,'0.00×');
assert.match(value().className,/neg/);
stats=calculate([{pnl:0},{pnl:0}]);
assert.equal(stats.value,null);
assert.equal(stats.state,'no-outcomes');
paint([{pnl:0},{pnl:0}]);
assert.equal(value().textContent,'—');
assert.match(explanation().textContent,/break-even/);
stats=calculate([]);
assert.equal(stats.value,null);
assert.equal(stats.state,'no-trades');
paint([]);
assert.match(explanation().textContent,/No closed trades/);
assert.equal(elements.get('#statProfitFactorGrossProfit').textContent,'—');
assert.equal(elements.get('#statProfitFactorGrossLoss').textContent,'—');
stats=calculate([{pnl:200},{pnl:null},{pnl:-25}]);
assert.equal(stats.value,null,'unknown P&L must not be treated as zero');
assert.equal(stats.missingPnlCount,1);
assert.equal(stats.state,'incomplete');
paint([{pnl:200},{pnl:null},{pnl:-25}]);
assert.equal(value().textContent,'—');
assert.match(explanation().textContent,/1 selected trade is missing recorded P&L/);

assert.match(html,/\.eq\('account_id',\s*tradingAccount\.id\)/,'closed trades remain scoped to the selected account');
assert.match(html,/\.eq\('position_status',\s*'closed'\)/,'source remains closed trades only');
assert.ok(html.includes("{id:'profit-factor',title:'Profit Factor'"),'Profit Factor is available in the Combined Outcomes indicator library');
assert.ok(html.includes("result['profit-factor']=profitFactor.state"),'the customizable Profit Factor card uses the validated existing calculation');
assert.ok(html.includes('id="statsOutcomeTabEquity"')&&html.includes('id="equityChart"'),'Equity Curve remains the first and default Combined Outcomes diagram');
assert.ok(html.includes('id="statsOutcomeTabDrawdown"')&&html.includes('buildDrawdownSeries(series.points)'),'Drawdown uses a verified account-equity series');
assert.match(html,/\.stats-indicator-grid \.stats-indicator-card\{\s*min-width:0;min-height:112px/,'indicator cards use compact dimensions');
assert.match(html,/@media\(max-width:520px\)\{\s*\.stats-indicator-stack\{grid-template-columns:1fr\}/,'indicator cards remain usable on mobile');

console.log('PASS Profit Factor states, currency, proportional comparison, and incomplete-data handling');
console.log('PASS Profit Factor remains selectable and the five combined-outcome diagrams are separated from specialist tabs');
